
"""
Component C - Function 2
Legal Brief Generation Input Models

Defines the inputs required to generate an
evidence-grounded legal brief.

Reuses the validated models from Function 1.
"""

from pydantic import BaseModel, ConfigDict, Field

from reasoning.input_models import ReasoningRequest
from reasoning.output_models import ReasoningResponse


class BriefGenerationRequest(BaseModel):
    """
    Input to the legal brief generation pipeline.

    source_request:
        Original question, facts, precedents,
        legislation and source passages.

    reasoning_result:
        Structured contextual reasoning
        generated by Function 1.

    title:
        Requested title for the draft brief.
    """

    model_config = ConfigDict(extra="forbid")

    source_request: ReasoningRequest

    reasoning_result: ReasoningResponse

    title: str = Field(
        default="Legal Research Brief",
        min_length=1
    )
