
"""
Component C - Function 2
Human-Readable Legal Brief Formatter

Converts a validated LegalBrief object into
a readable Markdown research document.

Features:
- Clear legal brief sections
- Individual claim identifiers
- Model-provided claim support labels
- Traceable evidence references
- Judicial-treatment metadata references
- Explicit limitations

This module only formats existing information.
It does not generate or verify legal reasoning.
"""

from brief.output_models import (
    BriefClaim,
    BriefEvidenceReference,
    LegalBrief,
)


BRIEF_SECTIONS = [
    ("Relevant Facts", "relevant_facts"),
    ("Applicable Legislation", "applicable_legislation"),
    ("Relevant Precedents", "relevant_precedents"),
    ("Precedent Treatment", "precedent_treatment"),
    ("Legal Analysis", "legal_analysis"),
    ("Arguments", "arguments"),
    ("Counterarguments", "counterarguments"),
    ("Application to Facts", "application_to_facts"),
    ("Conclusion", "conclusion"),
]


def format_evidence_reference(
    reference: BriefEvidenceReference
) -> str:
    """
    Convert one structured evidence reference
    into a human-readable citation label.

    This function does not create new citations.
    """

    # -----------------------------------------
    # Case passage
    # -----------------------------------------

    if reference.source_type == "case_passage":

        return (
            f"Case {reference.case_id}, "
            f"passage {reference.passage_id}"
        )

    # -----------------------------------------
    # Legislation
    # -----------------------------------------

    if reference.source_type == "legislation":

        if reference.legislation_name:
            label = reference.legislation_name

            if reference.act_id:
                label += f" ({reference.act_id})"

        else:
            label = reference.act_id or "Unidentified Act"

        if reference.section:
            label += f", {reference.section}"

        return label

    # -----------------------------------------
    # Original case fact
    # -----------------------------------------

    if reference.source_type == "case_fact":

        # Internally facts use zero-based indices.
        # Display them starting at 1 for readability.
        return f"Fact {reference.fact_index + 1}"

    # -----------------------------------------
    # Judicial-treatment metadata
    # -----------------------------------------

    if reference.source_type == "judicial_treatment":

        label = (
            "Judicial treatment: "
            f"{reference.source_case_id} "
            f"--{reference.treatment_status}--> "
            f"{reference.target_case_id}"
        )

        if reference.effective_date:
            label += (
                f"; effective {reference.effective_date.isoformat()}"
            )

        if reference.scope:
            label += f"; scope: {reference.scope}"

        return label

    # All known types are handled above.
    raise ValueError(
        f"Unsupported evidence type: {reference.source_type}"
    )


def format_brief_claim(
    claim: BriefClaim
) -> str:
    """
    Format one legal claim with its evidence.

    The claim support status is generated by
    the model, not independently established
    by this formatter.
    """

    status = claim.support_status.replace(
        "_", " "
    )

    lines = [
        f"**{claim.claim_id}** — *{status}*",
        "",
        claim.statement,
        "",
    ]

    if claim.evidence_references:

        references = [
            format_evidence_reference(reference)
            for reference in claim.evidence_references
        ]

        lines.append(
            "**Evidence:** " + "; ".join(references)
        )

    else:

        lines.append(
            "**Evidence:** No source reference cited."
        )

    return "\n".join(lines)


def format_legal_brief(
    brief: LegalBrief
) -> str:
    """
    Convert a LegalBrief into a complete
    human-readable Markdown document.

    Args:
        brief: A validated LegalBrief object.

    Returns:
        Markdown text containing all brief sections.

    This function does not modify the input brief.
    """

    lines = [
        f"# {brief.title}",
        "",
        "**Document Type:** Legal Research Brief",
        "",
        "**Status:** Research draft",
        "",
        (
            "**Evidence Notice:** Claim support labels "
            "reflect the generated brief. Citation "
            "identifiers may have passed structural "
            "grounding checks, but this document has "
            "not been independently verified for "
            "semantic or legal correctness."
        ),
        "",
        "---",
        "",
        "## Legal Issue",
        "",
        brief.legal_issue,
        "",
    ]

    # -----------------------------------------
    # Add each substantive section
    # -----------------------------------------

    for number, (heading, attribute) in enumerate(
        BRIEF_SECTIONS,
        start=1
    ):

        lines.append(
            f"## {number}. {heading}"
        )

        lines.append("")

        claims = getattr(brief, attribute)

        if not claims:

            lines.append(
                "No claims recorded in this section."
            )

            lines.append("")

            continue

        for claim in claims:

            lines.append(
                format_brief_claim(claim)
            )

            lines.append("")

    # -----------------------------------------
    # Add limitations
    # -----------------------------------------

    lines.append(
        f"## {len(BRIEF_SECTIONS) + 1}. Limitations"
    )

    lines.append("")

    if brief.limitations:

        for limitation in brief.limitations:

            lines.append(
                f"- {limitation}"
            )

    else:

        lines.append(
            "No explicit limitations were recorded "
            "in the generated brief."
        )

    # -----------------------------------------
    # Add document disclaimer
    # -----------------------------------------

    lines.extend([
        "",
        "---",
        "",
        (
            "*This is a legal research draft "
            "generated from supplied evidence. "
            "It is not a verified court filing "
            "or a substitute for professional "
            "legal review.*"
        ),
        "",
    ])

    return "\n".join(lines)
